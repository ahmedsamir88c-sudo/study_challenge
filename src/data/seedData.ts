// Generate 16 lectures for each subject
export function generateInitialLectures(subjects: AcademicSubject[]): AcademicLecture[] {
  const lectures: AcademicLecture[] = [];
  let idCounter = 1;

  for (const subject of subjects) {
    for (let lec = 1; lec <= 16; lec++) {
      lectures.push({
        id: idCounter++,
        subject_id: subject.id,
        lecture_number: lec,
        title: `المحاضرة ${lec}: ${getLectureTitle(subject.name, lec)}`,
        description: `محتوى ومفاهيم المحاضرة رقم ${lec} لمقرر ${subject.name}`,
        order: lec,
        has_content: true,
      });
    }
  }
  return lectures;
}

